"""MultiIndex DataFrame – Indexing and Slicing"""

import pandas as pd

index = pd.MultiIndex.from_tuples([
    ('A', 1), ('A', 2),
    ('B', 1), ('B', 2)
], names=['Category', 'Number'])

df = pd.DataFrame({
    'Value': [10, 20, 30, 40]
}, index=index)

print(df)

print("Indexing:")
print(df.loc['A'])

print("Slicing:")
print(df.loc['A':'B'])

"""MultiIndex with Category and SubCategory"""

