""" Data Aggregation – Group by Category"""

import pandas as pd
import numpy as np

df = pd.DataFrame({
    'Category': np.random.choice(['A', 'B', 'C'], 10),
    'Value': np.random.randint(10, 100, 10)
})

print(df)

result = df.groupby('Category')['Value'].agg(['sum', 'mean'])

print(result)

"""Group by Category and calculate total sales"""

import pandas as pd
import numpy as np

df = pd.DataFrame({
    'Product': ['Pen', 'Book', 'Pencil', 'Bag', 'Bottle'],
    'Category': np.random.choice(['A', 'B', 'C'], 5),
    'Sales': np.random.randint(100, 1000, 5)
})

print(df)

result = df.groupby('Category')['Sales'].sum()

print("Total Sales:")
print(result)

